/**
 * 扫描 public/downloads/，把最新安装包的信息生成成 src/data/download.generated.ts。
 *
 * 目的：以后发版只需要把新的 zip 放进 public/downloads/，构建时自动识别
 * 文件名、大小、版本和日期，页面配置不用再手改。
 */
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = resolve(here, "..");
const downloadsDir = join(siteRoot, "public", "downloads");
const outputFile = join(siteRoot, "src", "data", "download.generated.ts");

const MB = 1024 * 1024;

function formatSize(bytes) {
  const megabytes = bytes / MB;
  const rounded = megabytes >= 100 ? Math.round(megabytes) : Math.round(megabytes * 10) / 10;
  return `约 ${rounded} MB`;
}

function parseVersion(fileName) {
  const match = fileName.match(/v?(\d+)[._-](\d+)[._-](\d+)/i);
  return match ? `${Number(match[1])}.${Number(match[2])}.${Number(match[3])}` : "";
}

function formatReleasedAt(mtime) {
  const year = mtime.getFullYear();
  const month = String(mtime.getMonth() + 1).padStart(2, "0");
  return `${year}-${month}`;
}

function latestArtifact() {
  if (!existsSync(downloadsDir)) return null;
  const candidates = readdirSync(downloadsDir)
    .filter((name) => name.toLowerCase().endsWith(".zip"))
    .map((name) => {
      const full = join(downloadsDir, name);
      const stats = statSync(full);
      return { name, size: stats.size, mtime: stats.mtime };
    })
    .sort((a, b) => b.mtime.getTime() - a.mtime.getTime());
  return candidates[0] ?? null;
}

export function generateDownload() {
  const artifact = latestArtifact();
  const data = artifact
    ? {
        available: true,
        fileName: artifact.name,
        url: `/downloads/${artifact.name}`,
        size: formatSize(artifact.size),
        version: parseVersion(artifact.name),
        releasedAt: formatReleasedAt(artifact.mtime),
        generatedAt: new Date().toISOString()
      }
    : {
        available: false,
        fileName: "",
        url: "",
        size: "",
        version: "",
        releasedAt: "",
        generatedAt: new Date().toISOString()
      };

  const content = `// AUTO-GENERATED by scripts/generate-download.mjs — 不要手改。
// 发版流程：把新的 zip 放进 public/downloads/，重新 build（dev 下会自动刷新）。
export const downloadArtifact = ${JSON.stringify(data, null, 2)} as const;
`;

  mkdirSync(dirname(outputFile), { recursive: true });
  const previous = existsSync(outputFile) ? readFileSync(outputFile, "utf8") : "";
  if (previous === content) return data;
  writeFileSync(outputFile, content, "utf8");
  return data;
}

const isDirectRun = process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));
if (isDirectRun) {
  const data = generateDownload();
  console.log(data.available
    ? `[download] ${data.fileName} · ${data.size} · v${data.version || "?"} · ${data.releasedAt}`
    : "[download] public/downloads/ 里没有 zip，页面会显示“暂未发布”");
}
